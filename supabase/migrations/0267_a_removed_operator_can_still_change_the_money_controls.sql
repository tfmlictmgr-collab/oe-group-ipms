CREATE OR REPLACE FUNCTION public.my_notifications(p_days integer DEFAULT 30)
 RETURNS TABLE(id uuid, kind text, title text, body text, link text, read_at timestamp with time zone, created_at timestamp with time zone, entity_type text, entity_id uuid, target_live boolean)
 LANGUAGE sql
 STABLE
 SET search_path TO 'public'
AS $function$
  select
    n.id, n.kind, n.title, n.body, n.link, n.read_at, n.created_at,
    n.entity_type, n.entity_id,
    case
      when n.entity_id is null then true          -- a static link cannot dangle
      when n.entity_type = 'ticket'             then exists (select 1 from tickets t             where t.id = n.entity_id)
      when n.entity_type = 'payment'            then exists (select 1 from payments p            where p.id = n.entity_id)
      when n.entity_type = 'asset'              then exists (select 1 from assets a               where a.id = n.entity_id)
      when n.entity_type = 'property'           then exists (select 1 from properties r           where r.id = n.entity_id)
      when n.entity_type = 'lease'              then exists (select 1 from leases l                where l.id = n.entity_id)
      when n.entity_type = 'tenant_application' then exists (select 1 from tenant_applications a   where a.id = n.entity_id and a.purged_at is null)
      else true
    end
  from user_notifications n
  where n.user_id = active_uid()
    and (n.read_at is null or n.created_at >= now() - make_interval(days => greatest(p_days, 1)))
  order by n.read_at nulls first, n.created_at desc;
$function$
;

-- accept_tenancy_offer: guard injected after the opening begin.
CREATE OR REPLACE FUNCTION public.accept_tenancy_offer(p_token_hash text, p_invite_token_hash text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  o tenancy_offers%rowtype;
  a tenant_applications%rowtype;
  v_invite_id uuid;
  v_unit text;
begin
  -- Deactivation guard. Null-safe by construction: current_user_is_active()
  -- returns a boolean from exists(), never NULL, and the auth.uid() test keeps
  -- the service role (scheduled jobs, webhooks) passing straight through.
  if auth.uid() is not null and not current_user_is_active() then
    raise exception 'this account has been deactivated';
  end if;

  select * into o from tenancy_offers where accept_token_hash = p_token_hash for update;
  if o.id is null then
    raise exception 'this offer link is no longer valid';
  end if;
  if o.status <> 'issued' then
    raise exception 'this offer has already been %', o.status;
  end if;
  if o.expires_on < current_date then
    raise exception 'this offer lapsed on %', to_char(o.expires_on, 'DD Mon YYYY');
  end if;
  if coalesce(p_invite_token_hash, '') = '' then
    raise exception 'accepting needs an invitation token';
  end if;

  select * into a from tenant_applications where id = o.application_id;

  -- ⚠️ `issued_by`, not `auth.uid()`. There is no session here by definition —
  -- the person accepting has no account, which is the whole reason acceptance
  -- creates one. Stamping null would leave the invitation with no author, which
  -- is the fault 0142 had to go back and fix on remittances.
  insert into invitations (org_id, email, role, full_name, unit_id, token_hash, invited_by, expires_at)
  values (o.org_id, a.applicant_email, 'tenant', a.applicant_name, o.unit_id,
          p_invite_token_hash, o.issued_by, now() + interval '14 days')
  returning id into v_invite_id;

  update tenancy_offers
     set status = 'accepted', responded_at = now()
   where id = o.id;

  select label into v_unit from units where id = o.unit_id;

  perform notify_application_desk(
    a.id,
    'A tenancy offer was accepted',
    a.applicant_name || ' accepted the offer on ' || coalesce(v_unit, 'their unit') ||
    '. Record the tenancy to start billing it.'
  );

  return jsonb_build_object(
    'invitation_id', v_invite_id,
    'org_id', o.org_id,
    'application_id', a.id,
    'email', a.applicant_email,
    'name', a.applicant_name
  );
end;
$function$
;

-- operator_set_approval_chain: guard injected after the opening begin.
CREATE OR REPLACE FUNCTION public.operator_set_approval_chain(p_org_id uuid, p_shape text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_before text;
begin
  -- Deactivation guard. Null-safe by construction: current_user_is_active()
  -- returns a boolean from exists(), never NULL, and the auth.uid() test keeps
  -- the service role (scheduled jobs, webhooks) passing straight through.
  if auth.uid() is not null and not current_user_is_active() then
    raise exception 'this account has been deactivated';
  end if;

  if not caller_is_operator_admin() then
    raise exception 'only an OE Group operator administrator may set an organisation''s approval chain';
  end if;

  if p_shape is not null and p_shape not in ('standard', 'oea', 'single_stage') then
    raise exception 'unknown approval chain shape: %', p_shape;
  end if;

  select approval_chain_shape into v_before from orgs where id = p_org_id;
  if not found then
    raise exception 'no such organisation';
  end if;

  update orgs set approval_chain_shape = p_shape where id = p_org_id;

  -- Written explicitly rather than left to the generic table trigger: this is a
  -- change to a money control, and the audit row should say so in words an
  -- auditor reads, not as a column diff on an org record.
  insert into audit_log (org_id, actor_id, action, entity_type, entity_id,
                         before_state, after_state)
  values (
    p_org_id, auth.uid(), 'payment_chain.shape_changed', 'orgs', p_org_id,
    jsonb_build_object('approval_chain_shape', v_before),
    jsonb_build_object('approval_chain_shape', p_shape)
  );
end;
$function$
;

