-- A removed operator can still change an organisation's money controls
-- (7 Sept 2026).
--
-- Four functions, found by `verify-deactivation` section E asking the live
-- catalogue rather than by anyone reading a diff:
--
--   operator_set_approval_chain   (0248)  the chain SHAPE, per organisation
--   operator_set_approval_tiers   (0261)  whether the tier bands apply at all
--   accept_tenancy_offer          (0263)
--   my_notifications              (0221)  regressed — see below
--
-- ⚠️ The two `operator_set_*` are the ones that matter. `caller_is_operator_admin()`
-- asks for a role and an org and never asks whether the account is still live, so
-- an operator administrator who has been removed kept the ability to change
-- another organisation's approval ladder — a money control, and one decision 7
-- lists among those that "stay hardwired and never appear as toggles" precisely
-- because they are what an auditor checks. 0195's own subject was self-scoped
-- READS by a removed tenant; this is a write, one level up.
--
-- `accept_tenancy_offer` is a no-op on its ordinary path and is guarded anyway:
-- the person accepting has no account yet, so auth.uid() is null and the guard
-- passes straight through. "This one cannot be reached by a signed-in caller" is
-- an argument about today's callers, and the rule is about the class.
--
-- 📌 `my_notifications` was ALREADY fixed, by 0195, and came back. 0221 replaced
-- it to add the `target_live` column and was written from the pre-0195 body, so
-- the `active_uid()` substitution was silently undone — the same shape 0210
-- recorded when a `create or replace` reopened a revoke 0114 had closed. A replace
-- re-states the whole function, and whatever a previous migration put there that
-- the author did not know about is gone. Prose cannot prevent that; the generator
-- being re-runnable and the suite asking the catalogue is what caught it.
--
-- A follow-up to 0195, which established the rule: everything in `public`
-- reaching auth.uid() must resolve identity through a deactivation-aware path,
-- or be a declared exception. See 0195's header for what that was written
-- about and why the bodies below are generated rather than typed.
--
-- ⚠️ Generated by scripts/generate-deactivation-guards.mjs from
-- `pg_get_functiondef`. Regenerate rather than hand-editing.

