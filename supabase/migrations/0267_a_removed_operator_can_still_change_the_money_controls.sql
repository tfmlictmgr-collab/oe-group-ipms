                         before_state, after_state)
  values (
    p_org_id, auth.uid(), 'payment_chain.tiers_changed', 'orgs', p_org_id,
    jsonb_build_object('approval_tiers_enabled', v_before),
    jsonb_build_object('approval_tiers_enabled', coalesce(p_enabled, false))
  );
