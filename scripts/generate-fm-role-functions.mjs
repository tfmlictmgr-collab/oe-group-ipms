// The functions and view half of "a regional manager supersedes the FM/PM".
//
// Same reasoning as the policy generator: these bodies are read from the
// catalogue and substituted, not retyped. `archive_asset` and the vendor
// application decisions are gates; a body retyped from memory is where a clause
// goes missing.
import { fileURLToPath } from "node:url";
import path from "node:path";
import { writeFileSync } from "node:fs";
import { config } from "dotenv";
import pg from "pg";

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
config({ path: path.join(rootDir, ".env.local") });

const client = new pg.Client({
  host: process.env.SUPABASE_DB_HOST,
  port: Number(process.env.SUPABASE_DB_PORT || 5432),
  database: process.env.SUPABASE_DB_NAME,
  user: process.env.SUPABASE_DB_USER,
  password: process.env.SUPABASE_DB_PASSWORD,
  ssl: { rejectUnauthorized: false },
});
await client.connect();

const TARGETS = [
  "approve_vendor_application",
  "reject_vendor_application",
  "archive_asset",
  "restore_asset",
  "oversight_roles_with_fm",
];

const out = [];
for (const name of TARGETS) {
  const { rows } = await client.query(
    `select pg_get_functiondef(p.oid) as def
       from pg_proc p join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'public' and p.prokind = 'f' and p.proname = $1`,
    [name]
  );
  if (!rows.length) { console.log(`  MISSING ${name}`); continue; }

  let def = rows[0].def;
  const before = def;

  // Two shapes appear: a bare equality, and membership of a role array.
  def = def.split(`current_user_role() = 'facility_manager'::user_role`)
           .join(`current_user_role() = any (fm_roles())`);
  def = def.split(`v_role = 'facility_manager'`).join(`v_role = any (fm_roles())`);
  def = def.split(`'facility_manager'::user_role]`).join(`'facility_manager'::user_role, 'regional_manager'::user_role]`);
  def = def.split(`'admin','facility_manager'`).join(`'admin','facility_manager','regional_manager'`);
  def = def.split(`'facility_manager','admin'`).join(`'facility_manager','regional_manager','admin'`);
  def = def.split(`in ('admin', 'facility_manager')`).join(`in ('admin', 'facility_manager', 'regional_manager')`);

  if (def === before) {
    console.log(`  NO SUBSTITUTION MATCHED — ${name} (handle by hand)`);
    const fmLines = before.split("\n").filter((l) => l.includes("facility_manager"));
    for (const l of fmLines) console.log(`      ${l.trim().slice(0, 110)}`);
    continue;
  }
  console.log(`  rewrote ${name}`);
  out.push(def.trimEnd().endsWith(";") ? def : def + ";");
}

const { rows: vw } = await client.query(
  `select view_definition from information_schema.views
    where table_schema='public' and table_name='vendor_overview'`
);
if (vw.length) {
  let v = vw[0].view_definition;
  const before = v;
  v = v.split(`'facility_manager'::user_role]`).join(`'facility_manager'::user_role, 'regional_manager'::user_role]`);
  v = v.split(`= 'facility_manager'::user_role`).join(`= ANY (fm_roles())`);
  if (v !== before) {
    out.push(`create or replace view vendor_overview\nwith (security_invoker = on) as\n${v.trimEnd().replace(/;$/, "")};`);
    console.log("  rewrote vendor_overview");
  } else {
    console.log("  NO SUBSTITUTION MATCHED — vendor_overview");
  }
}

const header = `-- GENERATED by scripts/generate-fm-role-functions.mjs — reviewed before applying.
--
-- The functions and view that named \`facility_manager\` directly. Bodies read
-- from the catalogue and substituted, never retyped — \`archive_asset\` and the
-- vendor-application decisions are gates, and a clause lost in transcription is
-- exactly how the payment state machine was dropped in 0072b.

`;

const file = path.join(rootDir, "supabase", "migrations", "0078b_regional_manager_functions.sql");
writeFileSync(file, header + out.join("\n\n") + "\n", "utf8");
console.log(`\nWritten to ${path.relative(rootDir, file)}`);
await client.end();
