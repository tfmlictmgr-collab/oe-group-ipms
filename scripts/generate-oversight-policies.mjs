// Generates the SELECT-policy rewrite that gives `executive` oversight.
//
// Twenty-odd policies gate money and audit visibility by naming roles directly,
// because those capabilities are locked and therefore absent from the permission
// matrix. Hand-copying each definition into a migration is how a clause gets
// dropped and a policy silently widens, so the definitions are read from the live
// catalogue and rewritten mechanically. Output is reviewed before it is applied.
//
// The substitution replaces the rendered role array with `oversight_roles()` — one
// definition of who has oversight, instead of the same list in twenty places.
import { fileURLToPath } from "node:url";
import path from "node:path";
import { writeFileSync } from "node:fs";
import { config } from "dotenv";
import pg from "pg";

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
config({ path: path.join(rootDir, ".env.local") });

const client = new pg.Client({
  host: process.env.SUPABASE_DB_HOST,
  port: Number(process.env.SUPABASE_DB_PORT || 5432),
  database: process.env.SUPABASE_DB_NAME,
  user: process.env.SUPABASE_DB_USER,
  password: process.env.SUPABASE_DB_PASSWORD,
  ssl: { rejectUnauthorized: false },
});
await client.connect();

// Only SELECT policies. Oversight is reading and approving; it is not a licence to
// write bank configuration, post to the ledger, or run a reconciliation.
const { rows } = await client.query(`
  select schemaname, tablename, policyname, cmd, roles, qual, with_check
    from pg_policies
   where schemaname = 'public'
     and cmd = 'SELECT'
     and coalesce(qual,'') ~ 'finance_approver'
   order by tablename, policyname`);

const FIN2 = `(ARRAY['admin'::user_role, 'finance_approver'::user_role])`;
const FIN3 = `(ARRAY['admin'::user_role, 'facility_manager'::user_role, 'finance_approver'::user_role])`;

const out = [];
const skipped = [];

for (const p of rows) {
  let q = p.qual;
  let replaced = false;

  if (q.includes(FIN2)) { q = q.split(FIN2).join("(oversight_roles())"); replaced = true; }
  else if (q.includes(FIN3)) { q = q.split(FIN3).join("(oversight_roles_with_fm())"); replaced = true; }

  if (!replaced) { skipped.push(`${p.tablename}.${p.policyname}`); continue; }

  // pg returns `roles` as a Postgres array literal string, e.g. "{authenticated}",
  // not a JS array.
  const roleList = String(p.roles ?? "").replace(/^\{|\}$/g, "").split(",").filter(Boolean);
  const to = roleList.length && !roleList.includes("public") ? ` to ${roleList.join(", ")}` : "";
  out.push(
    `drop policy if exists ${p.policyname} on ${p.tablename};\n` +
    `create policy ${p.policyname} on ${p.tablename} for select${to}\n  using (${q});`
  );
}

const header = `-- GENERATED by scripts/generate-oversight-policies.mjs — reviewed before applying.
--
-- Every SELECT policy that gated visibility by naming 'admin' and
-- 'finance_approver' now asks \`oversight_roles()\` instead. The predicate is
-- otherwise byte-identical to what the live catalogue held, because it was read
-- from there rather than retyped.
--
-- What changes: \`executive\` — the MD of TFML, the Managing Partner of OEA — can
-- see what finance can see. What does not change: who may WRITE. No write policy
-- is touched here, so bank configuration, ledger posting and reconciliation stay
-- exactly where they were.

create or replace function oversight_roles()
returns user_role[] language sql immutable set search_path = public as $$
  select array['admin', 'finance_approver', 'executive']::user_role[];
$$;

create or replace function oversight_roles_with_fm()
returns user_role[] language sql immutable set search_path = public as $$
  select array['admin', 'facility_manager', 'finance_approver', 'executive']::user_role[];
$$;

comment on function oversight_roles is
  'Who may SEE the money and the audit trail. One definition instead of the same array in twenty policies — adding the next oversight role is one line here.';

`;

const file = path.join(rootDir, "supabase", "migrations", "0072a_oversight_read_policies.sql");
writeFileSync(file, header + out.join("\n\n") + "\n", "utf8");

console.log(`Rewrote ${out.length} SELECT policies:\n`);
for (const p of rows) if (!skipped.includes(`${p.tablename}.${p.policyname}`)) console.log(`  ${p.tablename}.${p.policyname}`);
if (skipped.length) {
  console.log(`\nNOT rewritten (role array in an unexpected shape — handle by hand):`);
  for (const s of skipped) console.log(`  ${s}`);
}
console.log(`\nWritten to ${path.relative(rootDir, file)}`);

await client.end();
