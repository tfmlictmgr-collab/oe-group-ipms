// Generates the policy rewrite that puts `regional_manager` beside
// `facility_manager` everywhere.
//
// Board position: a regional manager supersedes the FM/PM across the board — the
// same operational authority over a wider place. The permission matrix already
// says so, but locked capabilities are enforced by ROLE NAME in policies written
// before the role existed.
//
// Read from `pg_policies` and rewritten mechanically rather than retyped: 18
// predicates hand-copied into a migration is 18 chances to drop a clause, and
// these include the payment policies.
import { fileURLToPath } from "node:url";
import path from "node:path";
import { writeFileSync } from "node:fs";
import { config } from "dotenv";
import pg from "pg";

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
config({ path: path.join(rootDir, ".env.local") });

const client = new pg.Client({
  host: process.env.SUPABASE_DB_HOST,
  port: Number(process.env.SUPABASE_DB_PORT || 5432),
  database: process.env.SUPABASE_DB_NAME,
  user: process.env.SUPABASE_DB_USER,
  password: process.env.SUPABASE_DB_PASSWORD,
  ssl: { rejectUnauthorized: false },
});
await client.connect();

const { rows } = await client.query(`
  select tablename, policyname, cmd, roles, qual, with_check
    from pg_policies
   where schemaname = 'public'
     and (coalesce(qual,'') || coalesce(with_check,'')) like '%facility_manager%'
     and (coalesce(qual,'') || coalesce(with_check,'')) not like '%regional_manager%'
   order by tablename, policyname`);

const EQ = `current_user_role() = 'facility_manager'::user_role`;
const IN_ARRAY = `'facility_manager'::user_role`;

// `invitations_insert` is rewritten by hand in the migration: it needs the
// escalation rule as well, which no mechanical substitution can express.
const BY_HAND = new Set(["invitations_insert"]);

function widen(expr) {
  if (!expr) return null;
  let out = expr;
  // Bare equality → membership of the FM-or-above set.
  out = out.split(EQ).join(`current_user_role() = ANY (fm_roles())`);
  // Inside an existing role array → add the regional manager next to the FM.
  if (out.includes(IN_ARRAY)) {
    out = out.split(IN_ARRAY).join(`${IN_ARRAY}, 'regional_manager'::user_role`);
  }
  return out;
}

const out = [];
const skipped = [];

for (const p of rows) {
  if (BY_HAND.has(p.policyname)) { skipped.push(`${p.policyname} (by hand — needs the escalation rule)`); continue; }

  const qual = widen(p.qual);
  const check = widen(p.with_check);
  if (qual === p.qual && check === p.with_check) {
    skipped.push(`${p.tablename}.${p.policyname} (no substitution matched)`);
    continue;
  }

  const roleList = String(p.roles ?? "").replace(/^\{|\}$/g, "").split(",").filter(Boolean);
  const to = roleList.length && !roleList.includes("public") ? ` to ${roleList.join(", ")}` : "";
  const cmd = p.cmd.toLowerCase();

  let body = `drop policy if exists ${p.policyname} on ${p.tablename};\n`;
  body += `create policy ${p.policyname} on ${p.tablename} for ${cmd}${to}\n`;
  if (qual) body += `  using (${qual})`;
  if (qual && check) body += `\n`;
  if (check) body += `  with check (${check})`;
  body += `;`;
  out.push(body);
}

const header = `-- GENERATED by scripts/generate-fm-role-policies.mjs — reviewed before applying.
--
-- Every predicate below is byte-identical to what the live catalogue held, except
-- that \`regional_manager\` now sits beside \`facility_manager\`. Read from
-- pg_policies rather than retyped, because these include the payment policies and
-- a dropped clause there is a money bug.

create or replace function fm_roles()
returns user_role[] language sql immutable set search_path = public as $$
  -- A regional manager holds the same operational authority as a facility /
  -- properties manager, over a wider place. One definition, so the next time this
  -- set changes it changes in one file rather than eighteen policies.
  select array['facility_manager', 'regional_manager']::user_role[];
$$;

comment on function fm_roles is
  'FM/PM-or-above: the operational roles. A regional manager supersedes the facility/properties manager (board, 29 Jul 2026) — same authority, wider scope.';

`;

const file = path.join(rootDir, "supabase", "migrations", "0078a_regional_manager_supersedes_fm.sql");
writeFileSync(file, header + out.join("\n\n") + "\n", "utf8");

console.log(`Rewrote ${out.length} policies:\n`);
for (const p of rows) if (!BY_HAND.has(p.policyname)) console.log(`  ${p.tablename}.${p.policyname} [${p.cmd}]`);
if (skipped.length) {
  console.log(`\nNot rewritten:`);
  for (const s of skipped) console.log(`  ${s}`);
}
console.log(`\nWritten to ${path.relative(rootDir, file)}`);
await client.end();
